let currentLang = localStorage.getItem('siteLang') || 'uk';

function tr(key) {
    return (i18n[currentLang] && i18n[currentLang][key]) || i18n.uk[key] || key;
}

function applyTranslationValue(element, key, mode) {
    if (!element) return;
    const value = tr(key);
    if (mode === 'placeholder') {
        element.setAttribute('placeholder', value);
    } else if (mode === 'html') {
        element.innerHTML = value;
    } else if (mode === 'icon') {
        element.innerHTML = `<i class="fas fa-check-circle"></i> ${value}`;
    } else if (mode === 'telegramIcon') {
        element.innerHTML = `<i class="fab fa-telegram-plane"></i> ${value}`;
    } else if (mode === 'footerIcon') {
        const icon = element.querySelector('i');
        element.innerHTML = `${icon ? icon.outerHTML : ''} ${value}`;
    } else {
        element.textContent = value;
    }
}

function setElementText(element, key, mode = 'text') {
    if (element) {
        applyTranslationValue(element, key, mode);
    }
}

