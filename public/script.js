// Функція для перевірки імені та прізвища
function validateFullName(name) {
    const trimmedName = name.trim();
    const words = trimmedName.split(/\s+/);

    if (words.length < 2) {
        return { isValid: false, message: tr('errNameRequired') };
    }

    for (let word of words) {
        if (word.length < 2) {
            return { isValid: false, message: tr('errNameShort') };
        }
        if (!/^[\p{L}'-]+$/u.test(word)) {
            return { isValid: false, message: tr('errNameLetters') };
        }
    }

    return { isValid: true, message: '' };
}

function validateForm(data) {
    let isValid = true;

    if (!data.name || data.name.trim().length < 2) {
        showError('name', tr('errNameRequired'));
        isValid = false;
    } else {
        const nameValidation = validateFullName(data.name);
        if (!nameValidation.isValid) {
            showError('name', nameValidation.message);
            isValid = false;
        } else {
            clearError('name');
        }
    }

    if (!data.telegram || data.telegram.trim().length < 3) {
        showError('telegram', tr('errTelegram'));
        isValid = false;
    } else {
        clearError('telegram');
    }

    if (!data.budget) {
        showError('budget', tr('errBudget'));
        isValid = false;
    } else {
        clearError('budget');
    }

    if (budgetSelect && budgetSelect.value === 'custom') {
        const customBudget = customBudgetInput ? customBudgetInput.value : '';
        if (!customBudget || customBudget.trim() === '') {
            showError('budget', tr('errCustomBudget'));
            isValid = false;
        } else if (isNaN(customBudget) || Number(customBudget) <= 0) {
            showError('budget', tr('errCustomBudgetValid'));
            isValid = false;
        }
    }

    if (!data.description || data.description.trim().length < 10) {
        showError('description', tr('errDescription'));
        isValid = false;
    } else {
        clearError('description');
    }

    return isValid;
}

